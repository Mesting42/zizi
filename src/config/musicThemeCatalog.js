const localizeCatalogEntry = (entry, locale = 'zh') => {
  if (locale !== 'en') return entry

  return {
    ...entry,
    name: entry.nameEn || entry.name,
    caption: entry.captionEn || entry.caption,
    description: entry.descriptionEn || entry.description
  }
}

export const getLocalizedMusicIps = (locale = 'zh') => (
  MUSIC_IPS.map(ip => localizeCatalogEntry(ip, locale))
)

export const getLocalizedMusicThemePresets = (locale = 'zh') => (
  MUSIC_THEME_PRESETS.map(preset => localizeCatalogEntry(preset, locale))
)

export const getLocalizedMusicIp = (ipId, locale = 'zh') => (
  localizeCatalogEntry(MUSIC_IPS.find(ip => ip.id === ipId) || MUSIC_IPS[0], locale)
)

